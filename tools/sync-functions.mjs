#!/usr/bin/env node
/**
 * Mirrors the shared code that the Edge Function `api` needs into the function folder (D-083):
 *
 *   packages/{engine,shared}/src/**  ->  supabase/functions/_shared/packages/{engine,shared}/src/**
 *
 *   node tools/sync-functions.mjs           write the copy   (pnpm sync:functions)
 *   node tools/sync-functions.mjs --check   only compare it  (pnpm check:functions, part of pnpm lint)
 *
 * Which files: exactly the files reachable through relative imports from
 * packages/shared/src/index.ts (the only module the function imports). Tests, test helpers
 * (battle/testing.ts), golden data and READMEs are not reachable and therefore not copied.
 * The import graph is preferred over "every non-test file" because it is exact: the function
 * gets nothing it does not load, and a file that only tests use can never slip into the bundle.
 *
 * Every copied file is byte-identical to its original, so a plain comparison is the whole check.
 * The folder supabase/functions/_shared belongs to this script: in --check mode a missing,
 * different or additional file is an error, and the write mode deletes additional files.
 *
 * No dependencies besides Node itself.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = 'packages/shared/src/index.ts';
/** Source folders the copy may contain files from (relative to ROOT, forward slashes). */
const ALLOWED_SOURCES = ['packages/engine/src/', 'packages/shared/src/'];
export const TARGET = 'supabase/functions/_shared';
const README = 'README.md';
const FIX_HINT = 'Run `pnpm sync:functions` and commit the result.';

const README_TEXT = `# Generated copy: do not edit

This folder is generated by \`tools/sync-functions.mjs\`. It holds a byte-identical copy of the
files of \`packages/engine/src\` and \`packages/shared/src\` that the Edge Function \`api\` loads
(everything reachable from \`packages/shared/src/index.ts\`; no tests).

Why a copy: the Supabase GitHub integration deploys a function from \`supabase/functions\`
only, so the function must not import files outside of it (see docs/DECISIONS.md, D-083).

- Never edit these files by hand. Change the originals in \`packages/\` and run

      pnpm sync:functions

- \`pnpm check:functions\` (part of \`pnpm lint\` and CI) fails when this copy is missing,
  out of date or has extra files.
`;

/** Specifiers of static imports, re-exports, side-effect and dynamic imports. */
const IMPORT_PATTERNS = [
  /\bfrom\s*['"]([^'"]+)['"]/g,
  /\bimport\s*['"]([^'"]+)['"]/g,
  /\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
];

function toPosix(path) {
  return path.split(sep).join('/');
}

function isTestFile(rel) {
  return /\.test\.[cm]?[jt]sx?$/.test(rel);
}

/** Every relative file of the original reachable from ENTRY, sorted. Throws on a bad import. */
export function reachableFiles(root = ROOT) {
  const seen = new Set();
  const queue = [ENTRY];
  while (queue.length > 0) {
    const rel = queue.pop();
    if (seen.has(rel)) continue;
    const abs = join(root, rel);
    if (!existsSync(abs)) throw new Error(`${rel} is imported but does not exist`);
    if (!ALLOWED_SOURCES.some((dir) => rel.startsWith(dir))) {
      throw new Error(`${rel} is imported by the shared code but lies outside ${ALLOWED_SOURCES}`);
    }
    if (isTestFile(rel)) throw new Error(`${rel} is a test file but imported by non-test code`);
    seen.add(rel);
    const text = readFileSync(abs, 'utf8');
    for (const pattern of IMPORT_PATTERNS) {
      for (const match of text.matchAll(pattern)) {
        const spec = match[1];
        if (!spec.startsWith('.')) {
          throw new Error(
            `${rel} imports '${spec}'; the shared code may only use relative imports (D-083)`,
          );
        }
        queue.push(toPosix(relative(root, resolve(dirname(abs), spec))));
      }
    }
  }
  return [...seen].sort();
}

/** The wanted content of the copy: target path (relative to ROOT) -> Buffer. */
function wantedFiles(root = ROOT) {
  const out = new Map();
  for (const rel of reachableFiles(root)) {
    out.set(`${TARGET}/${rel}`, readFileSync(join(root, rel)));
  }
  out.set(`${TARGET}/${README}`, Buffer.from(README_TEXT, 'utf8'));
  return out;
}

/** Every file below `dir` (relative to ROOT, forward slashes). */
function listFiles(dir, root = ROOT) {
  const abs = join(root, dir);
  if (!existsSync(abs)) return [];
  const out = [];
  for (const entry of readdirSync(abs, { withFileTypes: true })) {
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...listFiles(rel, root));
    else out.push(rel);
  }
  return out;
}

/** Differences between the copy on disk and the wanted copy. */
export function compare(root = ROOT) {
  const wanted = wantedFiles(root);
  const present = new Set(listFiles(TARGET, root));
  const missing = [];
  const changed = [];
  for (const [path, content] of wanted) {
    if (!present.has(path)) missing.push(path);
    else if (!readFileSync(join(root, path)).equals(content)) changed.push(path);
  }
  const extra = [...present].filter((path) => !wanted.has(path)).sort();
  return { wanted, missing, changed, extra };
}

function removeEmptyDirs(dir) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) removeEmptyDirs(join(dir, entry.name));
  }
  if (readdirSync(dir).length === 0) rmSync(dir, { recursive: true });
}

/** Writes the copy below `root`: adds and updates files, removes additional ones. */
export function sync(root = ROOT) {
  const { wanted, missing, changed, extra } = compare(root);
  for (const path of [...missing, ...changed]) {
    const abs = join(root, path);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, wanted.get(path));
  }
  for (const path of extra) rmSync(join(root, path));
  removeEmptyDirs(join(root, TARGET));
  return {
    files: wanted.size,
    added: missing.length,
    updated: changed.length,
    removed: extra.length,
  };
}

function main(args) {
  if (args.includes('--check')) {
    const { wanted, missing, changed, extra } = compare();
    if (missing.length + changed.length + extra.length === 0) {
      console.log(`check:functions: ${TARGET} is up to date (${wanted.size} files).`);
      return 0;
    }
    console.error(`check:functions: the copy in ${TARGET} is out of date.`);
    for (const path of missing) console.error(`  missing:   ${path}`);
    for (const path of changed) console.error(`  different: ${path}`);
    for (const path of extra) console.error(`  extra:     ${path}`);
    console.error(FIX_HINT);
    return 1;
  }
  const r = sync();
  console.log(
    `sync:functions: ${r.files} files in ${TARGET} ` +
      `(${r.added} added, ${r.updated} updated, ${r.removed} removed).`,
  );
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error(`sync-functions: ${error instanceof Error ? error.message : String(error)}`);
    console.error(FIX_HINT);
    process.exitCode = 1;
  }
}
